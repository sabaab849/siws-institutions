/** The institution an event belongs to, as the Society names it. */
export type Institution =
  | 'Kindergarten'
  | 'Primary School'
  | 'Secondary School'
  | 'Junior College'
  | 'Degree College'
  | 'The Society';

/**
 * How much room a card takes in the grid: `feature` is two columns with a
 * large photograph, `wide` two columns with a letterbox one, `tall` a single
 * column with an upright photograph, and `small` a single column.
 */
export type EventSize = 'feature' | 'wide' | 'tall' | 'small';

export interface CampusEvent {
  title: string;
  institution: Institution;
  /** Year or season, only where the Society publishes one. */
  date?: string;
  description: string;
  image?: {
    src: string;
    /** 640px copy, for phones and tablets. */
    mobile: string;
    alt: string;
    /** object-position, where the subject is not in the middle of the frame. */
    position?: string;
  };
  size?: EventSize;
}

export interface EventCategory {
  slug: string;
  navLabel: string;
  title: string;
  intro: string;
  events: CampusEvent[];
  /** What SIWS still has to supply for this category. */
  missing?: string;
}

